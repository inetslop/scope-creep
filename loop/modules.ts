import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { warn } from './log.ts';
import { AGENTS_DIR, GAME_DIR, PLANNING_DIR, PROJECT } from './paths.ts';

/**
 * Module docs: one per gameplay module (augments, enemies, ...), so the PO plans against what really
 * exists instead of card prose. Humans write each module's guide in agents/prompts/<project>/modules/;
 * the runner adds the module's content, loaded from the game's own data, and writes the result to
 * planning/modules/ before every PO cycle (read-only for the PO). T0089 (Pulse) was Splash without
 * its cap plus Reach's added form, and nobody saw it: the PO only had the card lines.
 *
 * A guide's frontmatter:
 *   summary: one line, listed in the PO prompt
 *   content: folder in game/src/content whose registry fills "What exists" (optional)
 *   group_by: [first.kind, added]   fields to index "what shares a mechanic" by (optional)
 */
export const MODULES_SOURCE_DIR = path.join(AGENTS_DIR, 'prompts', PROJECT, 'modules');
export const MODULES_DIR = path.join(PLANNING_DIR, 'modules');
const CONTENT_DIR = path.join(GAME_DIR, 'src', 'content');

export interface ModuleGuide {
  name: string;
  summary: string;
  content?: string;
  groupBy: string[];
  body: string;
}

export function parseGuide(name: string, text: string): ModuleGuide {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(text);
  const meta: Record<string, string> = {};
  for (const line of (m?.[1] ?? '').split(/\r?\n/)) {
    const kv = /^(\w+):\s*(.*)$/.exec(line.trim());
    if (kv) meta[kv[1]!] = kv[2]!.trim();
  }
  const list = (v = ''): string[] => v.replace(/^\[|\]$/g, '').split(',').map((s) => s.trim()).filter(Boolean);
  return { name, summary: meta.summary ?? name, content: meta.content || undefined, groupBy: list(meta.group_by), body: text.slice(m?.[0].length ?? 0).trim() };
}

type Item = Record<string, unknown>;
/** Card text and other prose: shown as the item's quote, not as a field. */
const isProse = (v: unknown): v is string => typeof v === 'string' && v.length > 40;
const fmt = (v: unknown): string => (typeof v === 'number' ? String(Math.round(v * 1000) / 1000) : typeof v === 'string' ? v : JSON.stringify(v));

/** "kind pulse, damage 15, range 1.7"; nested objects inline as "slow {pct 0.4, sec 2}". Prose is left out. */
function fields(o: Item): string {
  return Object.entries(o)
    .filter(([, v]) => v !== undefined && !isProse(v))
    .map(([k, v]) => (v && typeof v === 'object' && !Array.isArray(v) ? `${k} {${fields(v as Item)}}` : `${k} ${fmt(v)}`))
    .join(', ');
}

/** The value at a dotted path; an object counts as the set of its field names ("added" -> "rangeMul"). */
function keyAt(item: Item, at: string): string | undefined {
  let v: unknown = item;
  for (const part of at.split('.')) v = v && typeof v === 'object' ? (v as Item)[part] : undefined;
  if (v === undefined || v === null) return undefined;
  if (typeof v === 'object' && !Array.isArray(v)) return Object.keys(v).sort().join(' + ') || '(none)';
  return fmt(v);
}

/** The generated part of a module doc: an index by shared mechanic, then every item with its data. */
export function renderContent(items: readonly Item[], groupBy: readonly string[]): string {
  const label = (it: Item): string => String(it.name ?? it.id);
  const out: string[] = [];
  for (const at of groupBy) {
    const groups = new Map<string, string[]>();
    for (const it of items) {
      const k = keyAt(it, at);
      if (k !== undefined) groups.set(k, [...(groups.get(k) ?? []), label(it)]);
    }
    out.push(`**By \`${at}\`** (items in one row share that mechanic: a new one joining a row must differ in more than numbers)`, '');
    for (const [k, names] of [...groups].sort()) out.push(`- \`${k}\`: ${names.join(', ')}`);
    out.push('');
  }
  for (const it of items) {
    out.push(`### ${label(it)}${it.id && it.id !== it.name ? ` (\`${fmt(it.id)}\`)` : ''}`);
    for (const [k, v] of Object.entries(it)) if (isProse(v)) out.push(`- ${k}: "${v}"`);
    for (const [k, v] of Object.entries(it)) {
      if (k === 'id' || k === 'name' || isProse(v) || v === undefined) continue;
      out.push(`- ${k}: ${v && typeof v === 'object' && !Array.isArray(v) ? fields(v as Item) : fmt(v)}`);
    }
    out.push('');
  }
  return out.join('\n').trimEnd();
}

function loadContent(folder: string): Item[] {
  const out = execFileSync(process.execPath, [path.join(import.meta.dirname, 'contentDump.ts'), CONTENT_DIR, folder], { encoding: 'utf8', timeout: 30_000, stdio: ['ignore', 'pipe', 'pipe'] });
  return JSON.parse(out) as Item[];
}

export function renderModuleDoc(guide: ModuleGuide, load: (folder: string) => Item[] = loadContent): string {
  const parts = [`<!-- Generated by the runner from agents/prompts/${PROJECT}/modules/${guide.name}.md and the game's content. Edits here are lost. -->`, '', guide.body];
  if (guide.content) {
    let data: string;
    try {
      const items = load(guide.content);
      data = `${items.length} in the game, from game/src/content/${guide.content}/ (the real values).\n\n${renderContent(items, guide.groupBy)}`;
    } catch (err) {
      warn(`module doc ${guide.name}: could not load game/src/content/${guide.content}: ${(err as Error).message.split('\n')[0]}`);
      data = '(Could not load the content this cycle; fall back to the inventory in your prompt.)';
    }
    parts.push('', '## What exists now', '', data);
  }
  return `${parts.join('\n').trimEnd()}\n`;
}

/** Writes planning/modules/<name>.md for every guide (and removes docs whose guide is gone). Returns the guides. */
export function writeModuleDocs(): ModuleGuide[] {
  const names = fs.existsSync(MODULES_SOURCE_DIR) ? fs.readdirSync(MODULES_SOURCE_DIR).filter((f) => f.endsWith('.md')).sort() : [];
  const guides = names.map((f) => parseGuide(path.basename(f, '.md'), fs.readFileSync(path.join(MODULES_SOURCE_DIR, f), 'utf8')));
  if (guides.length) fs.mkdirSync(MODULES_DIR, { recursive: true });
  for (const g of guides) fs.writeFileSync(path.join(MODULES_DIR, `${g.name}.md`), renderModuleDoc(g));
  for (const f of fs.existsSync(MODULES_DIR) ? fs.readdirSync(MODULES_DIR) : []) {
    if (!guides.some((g) => `${g.name}.md` === f)) fs.rmSync(path.join(MODULES_DIR, f), { force: true });
  }
  return guides;
}

/** The module list for the PO prompt. */
export function describeModules(guides: readonly ModuleGuide[]): string {
  return guides.length ? guides.map((g) => `- planning/modules/${g.name}.md: ${g.summary}`).join('\n') : '(none)';
}
