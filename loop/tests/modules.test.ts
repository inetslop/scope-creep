import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { describeModules, parseGuide, renderContent, renderModuleDoc } from '../modules.ts';

const splash = { id: 'splash', name: 'Splash', description: 'Blasts the 3 furthest around it. Added: hits burst over 1 cell.', first: { kind: 'pulse', damage: 15, range: 1.7, rate: 1 }, added: { splash: 1 } };
const reach = { id: 'reach', name: 'Reach', description: 'A sniper: long range, slow, heavy shots. Added: 35% more range.', first: { kind: 'shot', damage: 42, range: 4.6, rate: 0.45 }, added: { rangeMul: 1.35 } };
const pulse = { id: 'pulse', name: 'Pulse', description: 'A ring of damage around the tower itself, every 2 seconds.', first: { kind: 'pulse', damage: 8, range: 2.5, rate: 0.5 }, added: { rangeMul: 1.2 } };

describe('parseGuide', () => {
  it('reads the summary, content folder and group_by list, and keeps the body', () => {
    const g = parseGuide('augments', '---\nsummary: the cards\ncontent: augments\ngroup_by: [first.kind, added]\n---\n# Augments\n\nBody.\n');
    assert.deepEqual(g, { name: 'augments', summary: 'the cards', content: 'augments', groupBy: ['first.kind', 'added'], body: '# Augments\n\nBody.' });
  });
  it('works without frontmatter', () => {
    assert.deepEqual(parseGuide('waves', '# Waves'), { name: 'waves', summary: 'waves', content: undefined, groupBy: [], body: '# Waves' });
  });
});

describe('renderContent', () => {
  const text = renderContent([splash, reach, pulse], ['first.kind', 'added']);
  it('indexes items that share a mechanic: the same value, or the same fields of an object', () => {
    assert.match(text, /- `pulse`: Splash, Pulse/);
    assert.match(text, /- `rangeMul`: Reach, Pulse/);
    assert.match(text, /- `splash`: Splash\n/);
  });
  it('lists every item with its prose quoted and its data as fields', () => {
    assert.match(text, /### Splash \(`splash`\)\n- description: "Blasts the 3 furthest around it\. Added: hits burst over 1 cell\."\n- first: kind pulse, damage 15, range 1\.7, rate 1\n- added: splash 1/);
  });
});

describe('renderModuleDoc', () => {
  const guide = parseGuide('augments', '---\nsummary: s\ncontent: augments\ngroup_by: [first.kind]\n---\n# Augments');
  it('appends what exists, loaded from the content folder', () => {
    const doc = renderModuleDoc(guide, () => [splash]);
    assert.match(doc, /^<!-- Generated by the runner/);
    assert.match(doc, /# Augments\n\n## What exists now\n\n1 in the game, from game\/src\/content\/augments\//);
  });
  it('still writes the guide when the content cannot be loaded', () => {
    const doc = renderModuleDoc(guide, () => { throw new Error('boom'); });
    assert.match(doc, /Could not load the content this cycle/);
  });
});

describe('describeModules', () => {
  it('lists each doc with its summary for the PO prompt', () => {
    assert.equal(describeModules([parseGuide('enemies', '---\nsummary: what walks\n---\n')]), '- planning/modules/enemies.md: what walks');
  });
});
